/**
 * 取得特定神煞的阿修羅話術
 */
export function getAsuraWording(shenShaId: string): AsuraWordingLayer | undefined {
  return ASURA_WORDINGS[shenShaId];
}

/**
 * 驗證前端不得生成話術 — 這個函式只在後端調用
 * CI 測試會掃卡片前端代碼，禁止直接呼叫此函式或 ASURA_WORDINGS
 */
export function buildAsuraReadingCard(
  shenShaId: string,
  pillar: 'year' | 'month' | 'day' | 'hour'
): { coreDeclaration: string; pillarReading: string; transformationPath: string } | null {
  const wording = getAsuraWording(shenShaId);
  if (!wording) return null;

  return {
    coreDeclaration: wording.coreDeclaration,
    pillarReading: wording.pillarExtension[pillar],
    transformationPath: wording.transformationPath,
  };
}
