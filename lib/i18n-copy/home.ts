/** 首頁專用翻譯：先查本檔字典與裝飾字形，再套動態句型；fallback 用來查句型裡的卡片名稱（全站字典）。 */
export function createHomeTranslator(locale: HomeCopyLocale, fallback: Lookup): Lookup {
  const dict = homeCopy[locale];
  const glyphs = new Set(HOME_DECORATIVE_GLYPHS);
  const lookup: Lookup = text => dict[text] ?? fallback(text);
  return text => {
    if (glyphs.has(text)) return text;
    const hit = dict[text];
    if (hit !== undefined) return hit;
    for (const rule of RULES) {
      const m = text.match(rule.re);
      if (m) return rule.out[locale](m, lookup) || undefined;
    }
    return undefined;
  };
}
