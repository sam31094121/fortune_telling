const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm'), ts = require('typescript');
const mod = { exports:{} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/beast-result-voice.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module:mod,exports:mod.exports,setTimeout,clearTimeout});
const {createResultVoice}=mod.exports;
let calls=[], cancels=0, voices=[{lang:'en-US'},{lang:'zh-CN'},{lang:'zh-TW'}], status=[];
const synth={getVoices:()=>voices,speak:u=>calls.push(u),cancel:()=>cancels++};
const player=createResultVoice(synth,text=>({text}));
const report=s=>status.push(s);
player.speak('match1','獎賞：亢金龍一張',report,true);
assert.equal(calls.length,1); assert.equal(calls[0].voice.lang,'zh-TW');
calls[0].onstart(); calls[0].onend();
assert.deepEqual(status,['speaking','done']);
player.speak('match1','獎賞：亢金龍一張',report,true);
assert.equal(calls.length,1,'Remount cannot auto-announce the same receipt again');
player.speak('match1','獎賞：亢金龍一張',report);
assert.equal(calls.length,2,'Explicit replay only speaks the same text');
calls[1].onstart(); player.stop();
assert.equal(cancels,1); assert.equal(calls[1].onend,null,'Unmount removes callbacks and cancels owned audio');
player.speak('blocked','輸掉三張',report,true);
calls.at(-1).onerror({error:'not-allowed'}); assert.equal(status.at(-1),'unavailable');
player.speak('blocked','輸掉三張',report); assert.equal(calls.length,4,'Blocked playback remains retryable');
calls.at(-1).onend();
voices=[{lang:'en-US'}];
player.speak('no-chinese','獲勝',report); assert.equal(calls.length,4); assert.equal(status.at(-1),'unavailable');
voices=[{lang:'zh-CN'}];
player.speak('fallback','獲勝',report); assert.equal(calls.at(-1).lang,'zh-CN'); player.stop();
console.log('PASS: Chinese voice selection, result-only speech, once per receipt, explicit replay, blocked/unsupported fallback and cleanup');
